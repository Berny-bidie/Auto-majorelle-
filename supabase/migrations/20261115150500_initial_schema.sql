create table public.vehicles (
  id integer generated by default as identity primary key,
  brand_id integer not null references public.brands(id) on delete restrict,
  slug text not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  model text not null check (char_length(model) between 1 and 120),
  year integer not null check (year between 1950 and 2100),
  price_dh integer not null check (price_dh between 0 and 100000000),
  mileage_km integer not null check (mileage_km between 0 and 2000000),
  fuel text not null check (char_length(fuel) between 1 and 40),
  transmission text not null check (char_length(transmission) between 1 and 40),
  power_cv integer check (power_cv is null or power_cv between 0 and 3000),
  category text not null check (char_length(category) between 1 and 60),
  description text not null check (char_length(description) between 10 and 10000),
  equipment jsonb not null default '[]'::jsonb check (jsonb_typeof(equipment) = 'array'),
  images jsonb not null default '[]'::jsonb check (jsonb_typeof(images) = 'array'),
  availability text not null default 'available' check (availability in ('available', 'reserved', 'sold')),
  published boolean not null default false,
  featured boolean not null default false,
  warranty_note text,
  published_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.blog_posts (
