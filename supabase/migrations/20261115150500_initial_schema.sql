create table public.leads (
  id integer generated by default as identity primary key,
  submission_id uuid not null unique,
  type text not null check (type in ('contact', 'appointment', 'financing', 'trade_in')),
  name text not null check (char_length(name) between 2 and 160),
  email text check (email is null or char_length(email) <= 320),
  phone text not null check (char_length(phone) between 7 and 50),
  vehicle_slug text references public.vehicles(slug) on delete set null,
  message text not null default '' check (char_length(message) <= 4000),
  details jsonb not null default '{}'::jsonb check (jsonb_typeof(details) = 'object'),
  photo_paths text[] not null default '{}'::text[],
  status text not null default 'new' check (status in ('new', 'in_progress', 'completed')),
  source_ip_hash text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (details ->> 'consent' = 'true')
);

create table public.site_settings (
